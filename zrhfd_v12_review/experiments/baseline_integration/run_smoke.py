"""One immutable engineering integration run through the actual v1.2 worker.

Only the already-authorized same12_00 development query is selected. Algorithm
configs are generated by the root-owned scheduler without parameter overrides.
"""
from pathlib import Path
import argparse
import json
import sys
import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from experiments.common import sha, source_hashes, stamp, write_new
from experiments.schedule import configurations, execute
from zrhfd.graph import Graph

OUTPUT = 'reviews/baselines/integration_v12'
ROLE = 'engineering_integration_smoke_not_formal_quality_or_cost'


def prepare():
    folder = ROOT / OUTPUT
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / 'manifest.json'
    if path.exists():
        return json.loads(path.read_text())
    protocol_path = ROOT / 'experiments/protocol_v12.yaml'
    protocol = yaml.safe_load(protocol_path.read_text())
    catalog_path = ROOT / 'data/dev/same12/catalog.json'
    catalog = json.loads(catalog_path.read_text())
    case = next(c for c in catalog['cases'] if c['case_id'] == 'same12_00')
    if case['seed'] != 18:
        raise RuntimeError('Authorized development query changed')
    for field in ('graph', 'truth'):
        if sha(ROOT / case[field + '_path']) != case[field + '_sha256']:
            raise RuntimeError(field + ' input differs from catalog')
    communities = json.loads((ROOT / case['truth_path']).read_text())['communities']
    query = {k: case[k] for k in ('case_id', 'case_index', 'community_index',
             'seed', 'graph_path', 'graph_sha256', 'truth_path', 'truth_sha256',
             'n', 'edge_count', 'total_volume', 'seed_degree')}
    query.update(query_index=0, truth_vertices=communities[case['community_index']],
                 communities=communities, split='existing_development_only')
    graph = Graph.load(ROOT / case['graph_path'])
    oracle_volume = graph.stats(query['truth_vertices'])['volume']
    if oracle_volume != case['truth_volume']:
        raise RuntimeError('Offline oracle scalar differs from catalog')
    sources = {p: d for p, d in source_hashes().items() if
        p in ['experiments/catalog.py', 'experiments/common.py',
              'experiments/schedule.py', 'experiments/worker.py',
              'experiments/protocol_v12.yaml', 'experiments/ablations.py'] or
        (p.startswith('zrhfd/') and p.count('/') == 1 and p != 'zrhfd/storage.py') or
        (p.startswith('zrhfd/baselines/') and not p.endswith('/hypergraph.py'))}
    jobs = []
    configs = configurations(protocol, 'main')
    if len(configs) != 12:
        raise RuntimeError('Expected the current 12 ordinary configurations')
    for label, method, setting, config in configs:
        task = f"same12_00_q00_{label}"
        cfg = dict(config)
        if method != 'zrhfd':
            cfg['artifact_directory'] = f'{OUTPUT}/artifacts/{task}'
        job = {'task': task, 'method': method, 'setting': setting,
               'configuration': cfg, 'query': query,
               'result_path': f'{OUTPUT}/raw/{task}.json.gz',
               'source_sha256': sources, 'protocol_sha256': sha(protocol_path),
               'measurement_role': ROLE}
        jobpath = f'{OUTPUT}/jobs/{task}.json'
        write_new(ROOT / jobpath, job)
        jobs.append(jobpath)
    manifest = {'created_utc': stamp(), 'phase': 'main', 'jobs': jobs,
        'source_sha256': sources, 'protocol_sha256': sha(protocol_path),
        'catalog_sha256': sha(catalog_path), 'resources': protocol['resources'],
        'command': ['.venv/bin/python', 'experiments/baseline_integration/run_smoke.py'],
        'runner_sha256': sha(Path(__file__)), 'measurement_role': ROLE,
        'authorized_query': 'same12_00 seed18, existing development only',
        'oracle_scalar_for_oracle_jobs': oracle_volume,
        'quality_analysis': 'not performed; worker offline evaluation retained unchanged'}
    write_new(path, manifest)
    return manifest


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--prepare-only', action='store_true')
    parser.add_argument('--max-tasks', type=int)
    args = parser.parse_args()
    manifest = prepare()
    print('engineering_integration_jobs', len(manifest['jobs']), flush=True)
    if not args.prepare_only:
        execute(manifest, OUTPUT, args.max_tasks)


if __name__ == '__main__':
    main()
