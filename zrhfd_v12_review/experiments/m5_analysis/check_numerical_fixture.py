"""Run only in an authorized offline CPU slot: artificial paired-bootstrap check.

No graph, method, real quality data or figure is generated by this test.
"""
import copy
import json
import sys
import time
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from inventory import ROOT, digest
from summarize import bootstrap_panel, panel_summary, REPLICATES, SEED


def main():
    started = time.perf_counter()
    rows = []
    for qi, value in enumerate((.5, .75, .25, .625)):
        for method, f1 in (("zr_hfd", value), ("hfd_no_volume", value - .125)):
            rows.append({"dataset": "contact-high-school", "dataset_family": "contact-high-school", "cluster_code": "A" if qi < 2 else "B",
                "query_id": "ARTIFICIAL" + str(qi), "method": method, "analysis_status": "COMPLETED", "completed_budget_execution": True,
                "integrity_status": "PASS", "F1": f1, "controller_wall_seconds": 1. + qi})
    summary = panel_summary(rows)
    result = bootstrap_panel(rows, summary, fields=("F1", "controller_wall_seconds"))
    repeat = panel_summary(rows)
    repeated_result = bootstrap_panel(rows, repeat, fields=("F1", "controller_wall_seconds"))
    delta = summary["comparisons"]["zr_hfd_minus_hfd_no_volume"]["paired_F1_difference"]
    checks = [
        {"name": "frozen_bootstrap_replicates_and_seed", "passed": result["replicates"] == REPLICATES == 10000 and result["seed"] == SEED == 20261005},
        {"name": "paired_same_draw_preserves_constant_difference", "passed": delta["bootstrap_mean"]["percentile_95_CI"] == delta["bootstrap_median"]["percentile_95_CI"] == [.125, .125]},
        {"name": "all_replicates_valid_for_complete_pair", "passed": delta["bootstrap_mean"]["valid_replicates"] == delta["bootstrap_median"]["valid_replicates"] == 10000},
        {"name": "fixed_seed_deterministic", "passed": summary == repeat and result == repeated_result},
        {"name": "unobserved_methods_do_not_get_fake_CI", "passed": summary["methods"]["hfd_oracle"]["completed_only"]["F1"]["bootstrap_mean"] == {"percentile_95_CI": None, "valid_replicates": 0}},
        {"name": "fixed_contact_census_scope_explicit", "passed": "not population uncertainty" in result["scope"]},
    ]
    receipt = {"status": "PASS" if all(c["passed"] for c in checks) else "FAIL", "checks": checks,
        "scope": "Artificial numerical statistical fixture only; no real quality data, method, graph, performance claim or plot",
        "runtime_seconds_engineering_fixture_only": time.perf_counter() - started,
        "source_sha256": {str(p.relative_to(ROOT)): digest(p) for p in sorted((ROOT / "experiments/m5_analysis").glob("*.py"))}}
    target = ROOT / "reviews/m5_analysis/numerical_contract_receipt.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(receipt, indent=2) + "\n")
    print(json.dumps({"status": receipt["status"], "checks": len(checks), "runtime_seconds": receipt["runtime_seconds_engineering_fixture_only"]}))
    return 0 if receipt["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
